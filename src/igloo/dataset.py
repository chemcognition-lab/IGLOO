"""
Dataset management and preparation utilities for protein sequence datasets.

Supports loading and processing datasets from:
- Local data folder (data/*.csv)
- ProteinGym DMS assays (data/ProteinGym_DMS_Assays_Sub_processed/*.csv)
"""

import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd


@dataclass
class DatasetMetadata:
    """Metadata for a dataset."""
    name: str
    path: str
    size: int = 0
    sequence_column: str = "SEQ"
    target_column: str = "target"
    has_wildtype: bool = False
    wildtype_value: Optional[str] = None
    wildtype_identifier: Optional[str] = None
    protein_name: Optional[str] = None
    assay_type: Optional[str] = None
    source: str = "local"  # 'local' or 'proteingym'
    metadata: Dict = field(default_factory=dict)


class DatasetRegistry:
    """Registry of available datasets with discovery and loading utilities."""

    def __init__(self, data_root: str = "data"):
        """
        Initialize dataset registry.

        Args:
            data_root: Root directory for datasets (default: 'data')
        """
        self.data_root = Path(data_root)
        self.datasets: Dict[str, DatasetMetadata] = {}
        self._discover_datasets()

    def _discover_datasets(self) -> None:
        """Discover all available datasets in the data folder."""
        # Discover local datasets
        self._discover_local_datasets()

        # Discover ProteinGym datasets
        self._discover_proteingym_datasets()

        # Discover synthetic datasets
        self._discover_synthetic_datasets()

    def _discover_local_datasets(self) -> None:
        """Discover datasets in the main data folder."""
        if not self.data_root.exists():
            print(f"Warning: Data root '{self.data_root}' does not exist")
            return

        for csv_file in self.data_root.glob("*.csv"):
            name = csv_file.stem
            if name in self.datasets:
                continue  # Skip if already registered

            # Infer dataset properties
            metadata = self._infer_local_dataset_properties(name, csv_file)
            self.datasets[name] = metadata

    def _discover_proteingym_datasets(self) -> None:
        """Discover datasets in ProteinGym folder."""
        proteingym_root = self.data_root / "ProteinGym_DMS_Assays_Sub_processed"

        if not proteingym_root.exists():
            return

        for csv_file in proteingym_root.glob("*.csv"):
            name = csv_file.stem
            if name in self.datasets:
                continue  # Skip if already registered

            # Infer dataset properties from ProteinGym folder
            metadata = self._infer_proteingym_dataset_properties(name, csv_file)
            self.datasets[name] = metadata

    def _discover_synthetic_datasets(self) -> None:
        """Discover synthetic datasets generated by generate_synthetic_datasets.py."""
        synthetic_root = self.data_root / "synthetic"
        if not synthetic_root.exists():
            return

        for csv_file in sorted(synthetic_root.glob("*.csv")):
            name = csv_file.stem
            if name in self.datasets:
                continue

            metadata = self._infer_synthetic_dataset_properties(name, csv_file)
            self.datasets[name] = metadata

    def _infer_synthetic_dataset_properties(
        self, name: str, csv_path: Path
    ) -> "DatasetMetadata":
        """Infer metadata for a synthetic CSV (columns produced by SyntheticDatasetGenerator)."""
        try:
            df = pd.read_csv(csv_path, nrows=5)
            size = sum(1 for _ in open(csv_path)) - 1  # fast line count
        except Exception as e:
            print(f"Warning: Could not read {csv_path}: {e}")
            return DatasetMetadata(name=name, path=str(csv_path), source="synthetic")

        # Parse model + noise from filename, e.g. "GB1_additive_noise0.1"
        parts   = name.split("_")
        protein = parts[0] if parts else "unknown"
        model   = parts[1] if len(parts) > 1 else "unknown"
        noise   = parts[2].replace("noise", "") if len(parts) > 2 else "0.0"

        return DatasetMetadata(
            name=name,
            path=str(csv_path),
            size=size,
            sequence_column="SEQ",
            target_column="fitness",
            has_wildtype=True,
            wildtype_value="WT",
            wildtype_identifier="variant_column",
            source="synthetic",
            protein_name=protein,
            assay_type=model,
            metadata={
                "columns":    list(df.columns),
                "model":      model,
                "noise":      noise,
                "protein":    protein,
                "synthetic":  True,
            },
        )

    def _infer_local_dataset_properties(
        self, name: str, csv_path: Path
    ) -> DatasetMetadata:
        """Infer dataset properties from local CSV."""
        try:
            df = pd.read_csv(csv_path, nrows=10)
            size = len(pd.read_csv(csv_path))
        except Exception as e:
            print(f"Warning: Could not read {csv_path}: {e}")
            return DatasetMetadata(name=name, path=str(csv_path), source="local")

        # Infer column names
        seq_col = self._infer_sequence_column(df)
        target_col = self._infer_target_column(df)

        # Special handling for known datasets
        has_wt = False
        wt_value = None
        wt_identifier = None

        if "betalactamase" in name.lower():
            has_wt = True
            wt_identifier = "sequence"
            wt_value = "MSIQHFRVALIPFFAAFCLPVFAHPETLVKVKDAEDQLGARVGYIELDLNSGKILESFRPEERFPMMSTFKVLLCGAVLSRVDAGQEQLGRRIHYSQNDLVEYSPVTEKHLTDGMTVRELCSAAITMSDNTAANLLLTTIGGPKELTAFLHNMGDHVTRLDRWEPELNEAIPNDERDTTMPAAMATTLRKLLTGELLTLASRQQLIDWMEADKVAGPLLRSALPAGWFIADKSGAGERGSRGIIAALGPDGKPSRIVVIYTTGSQATMDERNRQIAEIGASLIKHW"
        elif "pafa" in name.lower():
            has_wt = True
            wt_identifier = "variant_column"
            wt_value = "WT"

        return DatasetMetadata(
            name=name,
            path=str(csv_path),
            size=size,
            sequence_column=seq_col,
            target_column=target_col,
            has_wildtype=has_wt,
            wildtype_value=wt_value,
            wildtype_identifier=wt_identifier,
            source="local",
            metadata={"columns": list(df.columns)},
        )

    def _infer_proteingym_dataset_properties(
        self, name: str, csv_path: Path
    ) -> DatasetMetadata:
        """Infer dataset properties from ProteinGym CSV."""
        try:
            df = pd.read_csv(csv_path, nrows=10)
            size = len(pd.read_csv(csv_path))
        except Exception as e:
            print(f"Warning: Could not read {csv_path}: {e}")
            return DatasetMetadata(
                name=name, path=str(csv_path), source="proteingym"
            )

        # ProteinGym typically has specific columns
        seq_col = self._infer_sequence_column(df)
        target_col = self._infer_target_column(df)

        # Extract protein and assay info from filename
        parts = name.split("_")
        protein_name = parts[0] if parts else None
        assay_type = "_".join(parts[1:]) if len(parts) > 1 else None

        return DatasetMetadata(
            name=name,
            path=str(csv_path),
            size=size,
            sequence_column=seq_col,
            target_column=target_col,
            protein_name=protein_name,
            assay_type=assay_type,
            source="proteingym",
            metadata={"columns": list(df.columns)},
        )

    @staticmethod
    def _infer_sequence_column(df: pd.DataFrame) -> str:
        """Infer the sequence column name from DataFrame."""
        # Common sequence column names
        sequence_names = ["SEQ", "sequence", "Sequence", "SEQUENCE", "seq", "protein_sequence"]
        for col in sequence_names:
            if col in df.columns:
                return col
        # Default to first string column
        for col in df.columns:
            if df[col].dtype == "object" and df[col].str.len().mean() > 10:
                return col
        return "SEQ"  # Fallback

    @staticmethod
    def _infer_target_column(df: pd.DataFrame) -> str:
        """Infer the target/activity column name from DataFrame."""
        # Common target column names
        target_names = [
            "activity",
            "Activity",
            "ACTIVITY",
            "quantitative_function",
            "score",
            "Score",
            "fitness",
            "Fitness",
            "log_fitness",
            "target",
            "Target",
            "value",
            "Effect",
            "effect",
        ]
        for col in target_names:
            if col in df.columns:
                return col
        # Default to first numeric column
        for col in df.columns:
            if pd.api.types.is_numeric_dtype(df[col]):
                return col
        return "target"  # Fallback

    def list_datasets(self, source: Optional[str] = None) -> List[str]:
        """
        List available datasets.

        Args:
            source: Filter by source ('local', 'proteingym', or None for all)

        Returns:
            List of dataset names
        """
        if source is None:
            return sorted(list(self.datasets.keys()))
        return sorted(
            [name for name, meta in self.datasets.items() if meta.source == source]
        )

    def get_dataset_info(self, dataset_name: str) -> Optional[DatasetMetadata]:
        """Get metadata for a specific dataset."""
        return self.datasets.get(dataset_name)

    def print_summary(self) -> None:
        """Print summary of discovered datasets."""
        print("\n" + "=" * 80)
        print("DATASET REGISTRY SUMMARY")
        print("=" * 80)

        local_datasets = self.list_datasets("local")
        print(f"\n LOCAL DATASETS ({len(local_datasets)}):")
        for name in local_datasets:
            meta = self.datasets[name]
            print(f"  • {name}")
            print(f"    Path: {meta.path}")
            print(f"    Size: {meta.size} sequences")
            print(f"    Sequence column: {meta.sequence_column}")
            print(f"    Target column: {meta.target_column}")
            if meta.has_wildtype:
                print(f"    Has wildtype: Yes ({meta.wildtype_identifier})")

        proteingym_datasets = self.list_datasets("proteingym")
        print(f"\n PROTEINGYM DATASETS ({len(proteingym_datasets)}):")
        for name in proteingym_datasets[:10]:  # Show first 10
            meta = self.datasets[name]
            print(f"  • {name}")
            print(f"    Protein: {meta.protein_name}, Assay: {meta.assay_type}")
            print(f"    Size: {meta.size} sequences")
        if len(proteingym_datasets) > 10:
            print(f"  ... and {len(proteingym_datasets) - 10} more datasets")

        synthetic_datasets = self.list_datasets("synthetic")
        print(f"\n SYNTHETIC DATASETS ({len(synthetic_datasets)}):")
        for name in synthetic_datasets:
            meta = self.datasets[name]
            model = meta.metadata.get("model", "?")
            noise = meta.metadata.get("noise", "?")
            print(f"  • {name}")
            print(f"    Protein: {meta.protein_name}, Model: {model}, Noise: {noise}")
            print(f"    Size: {meta.size} sequences")

        print("\n" + "=" * 80)


class Dataset:
    """Base class for protein sequence datasets."""

    def __init__(
        self,
        dataframe: pd.DataFrame,
        metadata: DatasetMetadata,
        config: Optional[Dict] = None,
    ):
        """
        Initialize a dataset.

        Args:
            dataframe: The dataset DataFrame
            metadata: Dataset metadata
            config: Optional configuration dictionary
        """
        self.df = dataframe
        self.metadata = metadata
        self.config = config or {}

        # Extract sequences and raw targets
        self.sequences = self.df[metadata.sequence_column].astype(str).tolist()
        self.targets = self.df[metadata.target_column].values

        # Pipeline-compatible attributes — populated by prepare()
        self.y_raw: Optional[np.ndarray] = None
        self.y: Optional[np.ndarray] = None
        self.y_log_mean: Optional[float] = None
        self.y_log_std: Optional[float] = None
        self.wt_seq: Optional[str] = None
        self.wt_idx: int = -1
        self._prepared: bool = False

    def __len__(self) -> int:
        """Return dataset size."""
        return len(self.df)

    def __repr__(self) -> str:
        """String representation of dataset."""
        return (
            f"Dataset(name='{self.metadata.name}', "
            f"size={len(self)}, "
            f"source='{self.metadata.source}')"
        )

    def get_sequence_stats(self) -> Dict[str, float]:
        """Get statistics about sequences."""
        lengths = [len(seq) for seq in self.sequences]
        return {
            "count": len(self.sequences),
            "min_length": min(lengths),
            "max_length": max(lengths),
            "mean_length": np.mean(lengths),
            "std_length": np.std(lengths),
        }

    def get_target_stats(self) -> Dict[str, float]:
        """Get statistics about targets."""
        targets = self.targets[~np.isnan(self.targets)]
        return {
            "count": len(targets),
            "min": float(np.min(targets)),
            "max": float(np.max(targets)),
            "mean": float(np.mean(targets)),
            "std": float(np.std(targets)),
            "median": float(np.median(targets)),
        }

    def prepare(self, config: Dict) -> "Dataset":
        """
        Apply the full preprocessing pipeline to make this Dataset compatible
        with run_integrated_gradients.py.

        Performs (in order):
          1. NaN / Inf replacement in the target column
          2. Dataset-specific overrides (betalactamase WT target -> 1.0)
          3. Z-score or no-op normalization -> sets y, y_log_mean, y_log_std
          4. Wildtype sequence identification -> sets wt_seq, wt_idx

        Args:
            config: Configuration dict in the same format used by the pipeline
                    (must contain data.target_column, data.normalization,
                    and data.wildtype).

        Returns:
            self  (allows chaining: dataset.prepare(config).to_pipeline_tuple())
        """
        from .config_utils import get_wildtype_sequence

        target_col = config['data']['target_column']
        dataset_name = config['data'].get('name', self.metadata.name).lower()

        # 1. Replace NaN / Inf
        self.df[target_col] = self.df[target_col].fillna(0.0)
        self.df[target_col] = self.df[target_col].replace([np.inf, -np.inf], 0.0)

        # 2. Dataset-specific preprocessing
        if dataset_name == 'betalactamase':
            wt_config = config['data']['wildtype']
            try:
                _wt_seq, _wt_idx = get_wildtype_sequence(self.df, wt_config)
                if _wt_idx >= 0:
                    original_value = self.df.loc[_wt_idx, target_col]
                    self.df.loc[_wt_idx, target_col] = 1.0
                    print(f"Set betalactamase wildtype target from {original_value:.4f} to 1.0")
            except Exception as e:
                print(f"Warning: Could not set betalactamase wildtype target: {e}")
        else:
            print(f"Dataset '{dataset_name}' - skipping wildtype target override")

        # 3. Refresh raw targets after any overrides
        self.y_raw = self.df[target_col].values.astype(np.float32)
        self.targets = self.y_raw

        print(f"Target range: {np.min(self.y_raw):.4f} to {np.max(self.y_raw):.4f}")

        # 4. Normalization
        normalization = config['data'].get('normalization', 'z-score')
        if normalization == 'z-score':
            self.y_log_mean = float(np.mean(self.y_raw))
            self.y_log_std = float(np.std(self.y_raw))
            self.y = (self.y_raw - self.y_log_mean) / self.y_log_std
            print(
                f"Z-score normalization applied: mean={self.y_log_mean:.4f}, "
                f"std={self.y_log_std:.4f}"
            )
            print(f"Normalised target range: {np.min(self.y):.4f} to {np.max(self.y):.4f}")
        elif normalization in ('none', None):
            print("Using raw target values without normalization.")
            self.y = self.y_raw.copy()
            self.y_log_mean = 0.0
            self.y_log_std = 1.0
        else:
            raise ValueError(f"Unknown normalization method: {normalization}")

        # 5. Wildtype identification
        wt_config = config['data']['wildtype']
        try:
            self.wt_seq, self.wt_idx = get_wildtype_sequence(self.df, wt_config)
        except Exception as e:
            print(f"Warning: Could not identify wildtype sequence: {e}")
            self.wt_seq = None
            self.wt_idx = -1

        self._prepared = True
        return self

    def to_pipeline_tuple(self) -> Tuple:
        """
        Return a 6-tuple that is drop-in compatible with the output of
        load_and_prepare_data() in data_processing.py.

        Returns:
            (df, sequences, y_raw, y, y_log_mean, y_log_std)

        Raises:
            RuntimeError: If prepare(config) has not been called first.
        """
        if not self._prepared:
            raise RuntimeError(
                "Call dataset.prepare(config) before dataset.to_pipeline_tuple()"
            )
        return (self.df, self.sequences, self.y_raw, self.y, self.y_log_mean, self.y_log_std)

    def get_wildtype(self) -> Tuple[Optional[str], int]:
        """
        Return the wildtype sequence and its row index.

        Returns:
            (wt_seq, wt_idx) - compatible with prepare_wildtype_sequence() output.

        Raises:
            RuntimeError: If prepare(config) has not been called first.
        """
        if not self._prepared:
            raise RuntimeError(
                "Call dataset.prepare(config) before dataset.get_wildtype()"
            )
        return self.wt_seq, self.wt_idx

    def print_summary(self) -> None:
        """Print dataset summary."""
        print("\n" + "=" * 80)
        print(f"DATASET: {self.metadata.name.upper()}")
        print("=" * 80)

        print(f"\n📊 Basic Information:")
        print(f"  Source: {self.metadata.source}")
        print(f"  Path: {self.metadata.path}")
        print(f"  Size: {len(self)} sequences")

        seq_stats = self.get_sequence_stats()
        print(f"\n🧬 Sequence Statistics:")
        print(f"  Length range: {seq_stats['min_length']} - {seq_stats['max_length']}")
        print(f"  Mean length: {seq_stats['mean_length']:.1f}")
        print(f"  Std dev: {seq_stats['std_length']:.1f}")

        target_stats = self.get_target_stats()
        print(f"\n📈 Target Statistics:")
        print(f"  Range: {target_stats['min']:.4f} - {target_stats['max']:.4f}")
        print(f"  Mean: {target_stats['mean']:.4f}")
        print(f"  Std dev: {target_stats['std']:.4f}")
        print(f"  Median: {target_stats['median']:.4f}")

        if self.metadata.has_wildtype:
            print(f"\n⭐ Wildtype Information:")
            print(f"  Has wildtype: Yes")
            print(f"  Identifier type: {self.metadata.wildtype_identifier}")

        print("\n" + "=" * 80)


class DatasetLoader:
    """Utility for loading and managing datasets."""

    def __init__(self, data_root: str = "data"):
        """
        Initialize dataset loader.

        Args:
            data_root: Root directory for datasets
        """
        self.registry = DatasetRegistry(data_root)
        self.loaded_datasets: Dict[str, Dataset] = {}

    def load(
        self, dataset_name: str, config: Optional[Dict] = None
    ) -> Optional[Dataset]:
        """
        Load a dataset by name.

        Args:
            dataset_name: Name of the dataset to load
            config: Optional configuration dictionary

        Returns:
            Dataset object or None if not found
        """
        # Check if already loaded
        if dataset_name in self.loaded_datasets:
            return self.loaded_datasets[dataset_name]

        # Get metadata
        metadata = self.registry.get_dataset_info(dataset_name)
        if metadata is None:
            print(f"Error: Dataset '{dataset_name}' not found in registry")
            return None

        # Load CSV
        try:
            df = pd.read_csv(metadata.path)
        except Exception as e:
            print(f"Error loading dataset '{dataset_name}': {e}")
            return None

        # Create dataset object
        dataset = Dataset(df, metadata, config)
        self.loaded_datasets[dataset_name] = dataset

        return dataset

    def load_multiple(
        self, dataset_names: List[str], config: Optional[Dict] = None
    ) -> Dict[str, Dataset]:
        """
        Load multiple datasets.

        Args:
            dataset_names: List of dataset names to load
            config: Optional configuration dictionary

        Returns:
            Dictionary mapping dataset names to Dataset objects
        """
        results = {}
        for name in dataset_names:
            dataset = self.load(name, config)
            if dataset is not None:
                results[name] = dataset
        return results

    def load_by_source(
        self, source: str, config: Optional[Dict] = None
    ) -> Dict[str, Dataset]:
        """
        Load all datasets from a specific source.

        Args:
            source: Source to filter by ('local' or 'proteingym')
            config: Optional configuration dictionary

        Returns:
            Dictionary mapping dataset names to Dataset objects
        """
        dataset_names = self.registry.list_datasets(source)
        return self.load_multiple(dataset_names, config)

    def load_prepared(
        self, dataset_name: str, config: Dict
    ) -> Optional["Dataset"]:
        """
        Load a dataset and run the full preprocessing pipeline so it is
        immediately compatible with run_integrated_gradients.py.

        Equivalent to:
            dataset = loader.load(dataset_name)
            dataset.prepare(config)

        After calling this you can use:
            df, sequences, y_raw, y, y_log_mean, y_log_std = dataset.to_pipeline_tuple()
            wt_seq, wt_idx = dataset.get_wildtype()

        Args:
            dataset_name: Name of the dataset to load
            config: Pipeline configuration dict

        Returns:
            Prepared Dataset object, or None if loading failed.
        """
        dataset = self.load(dataset_name)
        if dataset is None:
            return None
        dataset.prepare(config)
        return dataset

    def get_available_datasets(self) -> List[str]:
        """Get list of available datasets."""
        return self.registry.list_datasets()

    def print_registry_summary(self) -> None:
        """Print summary of available datasets."""
        self.registry.print_summary()


# Convenience functions for quick access
def discover_datasets(data_root: str = "data") -> DatasetRegistry:
    """
    Discover and return available datasets.

    Args:
        data_root: Root directory for datasets

    Returns:
        DatasetRegistry object
    """
    return DatasetRegistry(data_root)


def load_dataset(
    dataset_name: str, data_root: str = "data", config: Optional[Dict] = None
) -> Optional[Dataset]:
    """
    Load a single dataset by name.

    Args:
        dataset_name: Name of the dataset to load
        data_root: Root directory for datasets
        config: Optional configuration dictionary

    Returns:
        Dataset object or None if not found
    """
    loader = DatasetLoader(data_root)
    return loader.load(dataset_name, config)


def load_datasets(
    dataset_names: List[str], data_root: str = "data", config: Optional[Dict] = None
) -> Dict[str, Dataset]:
    """
    Load multiple datasets.

    Args:
        dataset_names: List of dataset names to load
        data_root: Root directory for datasets
        config: Optional configuration dictionary

    Returns:
        Dictionary mapping dataset names to Dataset objects
    """
    loader = DatasetLoader(data_root)
    return loader.load_multiple(dataset_names, config)


def list_datasets(data_root: str = "data", source: Optional[str] = None) -> List[str]:
    """
    List available datasets.

    Args:
        data_root: Root directory for datasets
        source: Filter by source ('local', 'proteingym', or None for all)

    Returns:
        List of dataset names
    """
    registry = DatasetRegistry(data_root)
    return registry.list_datasets(source)
