#!/usr/bin/env python3
"""Generate IGLOO configs for all ProteinGym DMS datasets.

Reads wildtype_sequences.fasta to get WT sequences, then creates one
YAML config per *_train.csv file under data/ProteinGym_DMS_Assays_Sub_processed/.

Output: configs/ProteinGym/{dataset_name}_config.yaml
"""

import os
import re
from pathlib import Path

# ── Paths ──────────────────────────────────────────────────────────────────
PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_ROOT / "data" / "ProteinGym_DMS_Assays_Sub_processed"
FASTA_PATH = DATA_DIR / "wildtype_sequences.fasta"
OUT_DIR = PROJECT_ROOT / "configs" / "ProteinGym"
OUT_DIR.mkdir(parents=True, exist_ok=True)

# ── Parse FASTA ────────────────────────────────────────────────────────────
def parse_fasta(path: Path) -> dict[str, str]:
    seqs = {}
    name = None
    seq_parts = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line.startswith(">"):
                if name is not None:
                    seqs[name] = "".join(seq_parts)
                name = line[1:].strip()
                seq_parts = []
            else:
                seq_parts.append(line)
    if name is not None:
        seqs[name] = "".join(seq_parts)
    return seqs

wt_seqs = parse_fasta(FASTA_PATH)
print(f"Loaded {len(wt_seqs)} WT sequences from FASTA.")

# ── Config template ────────────────────────────────────────────────────────
TEMPLATE = """\
# ProteinGym DMS dataset: {dataset_name}
# Auto-generated by scripts/generate_proteingym_configs.py

data:
  name: "{dataset_name}"
  path: "data/ProteinGym_DMS_Assays_Sub_processed/{dataset_name}_train.csv"
  target_column: "quantitative_function"
  normalization: "z-score"
  wildtype:
    method: "sequence"
    sequence: "{wt_seq}"

training:
  test_fraction: 0.0          # use pre-split test file instead
  test_path: "data/ProteinGym_DMS_Assays_Sub_processed/{dataset_name}_test.csv"
  n_folds: 5
  seed: 42

model:
  esm_model_name: "esmc_300m"
  esm_layer: 33
  pooling_method: "esm_attention"
  hidden_dim1: 1024
  hidden_dim2: 512
  hidden_dim3: 256
  hidden_dim4: 128
  dropout_rate: 0.15
  learning_rate: 0.0002
  batch_size: 128
  epochs: 150
  loss_type: "huber"
  final_activation: null

integrated_gradients:
  method: "embedding"
  attribution_method: "signed"
  interpolation_path: "linear"
  steps: 500
  batch_size: 10

analysis:
  sequence_selection:
    include_extremes: true
    include_median: true
    include_top_n: 0
    include_bottom_n: 0
    include_all: false
    custom_sequences: []

results_dir: "results/ProteinGym/{dataset_name}"
force_retrain: false
"""

# ── Generate configs ───────────────────────────────────────────────────────
train_files = sorted(DATA_DIR.glob("*_train.csv"))
print(f"Found {len(train_files)} train CSV files.")

skipped = []
generated = []

for train_file in train_files:
    dataset_name = train_file.stem.replace("_train", "")
    wt_seq = wt_seqs.get(dataset_name)

    if wt_seq is None:
        print(f"  WARNING: no WT sequence for '{dataset_name}' — skipping.")
        skipped.append(dataset_name)
        continue

    out_path = OUT_DIR / f"{dataset_name}_config.yaml"
    out_path.write_text(TEMPLATE.format(dataset_name=dataset_name, wt_seq=wt_seq))
    generated.append(dataset_name)

print(f"\nGenerated {len(generated)} configs → {OUT_DIR}")
if skipped:
    print(f"Skipped {len(skipped)} (no WT sequence): {skipped}")
